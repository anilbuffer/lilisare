export interface CaregiverCustomField {
  label: string;
  value: string;
  category: string;
}

export interface CaregiverFormItem {
  id: string;
  title: string;
  type: string;
  dateSigned: string;
  status: "Completed" | "Pending Signature" | "Needs Review";
  signedBy: string;
}

export interface CaregiverPointHistory {
  id: string;
  date: string;
  reason: string;
  points: number;
  type: "positive" | "negative";
}

export interface CaregiverNoteItem {
  id: string;
  date: string;
  author: string;
  role: string;
  category: "General" | "Scheduling" | "Clinical" | "HR";
  content: string;
}

export interface CaregiverAvailabilityBlock {
  day: "Monday" | "Tuesday" | "Wednesday" | "Thursday" | "Friday" | "Saturday" | "Sunday";
  isAvailable: boolean;
  morning: boolean; // 8am - 12pm
  afternoon: boolean; // 12pm - 5pm
  evening: boolean; // 5pm - 9pm
  night: boolean; // 9pm - 8am
  notes?: string;
}

export interface AdminCaregiverItem {
  id: string;
  numericId?: string; // e.g. "232", "36", "19", "462"
  name: string;
  sortName?: string; // e.g. "Carter, Carole"
  role: string;
  status: "Active" | "Onboarding" | "On Hold" | "Inactive";
  extStatus?: string; // e.g. "Active", "Verified"
  administrator?: string; // e.g. "Mackenzie Bertelsman", "Will Martin", "Sydney Garsee", "AxisCare Data Entry"
  gender?: string; // e.g. "Female", "Male"
  classes?: string[]; // e.g. ["Certified Nurse Aide", "Homemaker"]
  homePhone?: string; // e.g. "555-555-5555"
  mobilePhone?: string; // e.g. "555-555-5555"
  rating: number;
  complianceRate: number;
  activePatients: number;
  lastActive: string;
  phone: string;
  email: string;
  location?: string; // e.g. "5525 Clovercrest Dr. , Brentwood, TN, 37027"
  age?: number | string;
  branch?: string;
  classification?: "W-2" | "1099" | "Family Paid Exempt";
}

